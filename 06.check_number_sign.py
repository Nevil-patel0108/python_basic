# Ask the user to enter a number and convert the input (string) to an integer
x = int(input("Enter a number : "))

# Check if the number is greater than 0
if x > 0:
    print("Positive")  # Runs only when x is positive

# Check if the number is less than or equal to 0
if x <= 0:
    print("non positive")  # Runs when x is zero or negative
